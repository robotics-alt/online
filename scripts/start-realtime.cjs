const path = require('node:path')
const { spawn } = require('node:child_process')
const root = path.resolve(__dirname, '..')
require('@next/env').loadEnvConfig(root)
if (!process.env.SESSION_SECRET || process.env.SESSION_SECRET.length < 32 || /^(replace|tutorsphere-dev-secret)/i.test(process.env.SESSION_SECRET)) throw Error('Set the same SESSION_SECRET as the web app')
const child = spawn(process.env.BUN_BIN || 'bun', ['run', 'mini-services/realtime-service/index.ts'], { cwd: root, env: process.env, stdio: 'inherit', windowsHide: true })
child.on('error', error => { console.error(error.message); process.exitCode = 1 })
child.on('exit', code => { process.exitCode = code || 0 })
for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => child.kill(signal))
